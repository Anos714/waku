import { z } from "zod";
import { SOCIAL_PLATFORMS } from "@/lib/profile/platforms";

/* ---------------------------------------------------------------------------
   URL safety
   Only http/https/mailto/tel are treated as navigable. Anything else
   (javascript:, data:, file:, vbscript:, ...) is rejected so public profile
   pages can never link to unsafe schemes.
--------------------------------------------------------------------------- */

const ALLOWED_PROTOCOLS = ["http:", "https:", "mailto:", "tel:"];

export function isSafeUrl(value: string): boolean {
  if (!value) return false;
  try {
    const trimmed = value.trim();
    // Allow scheme-less URLs that look like domains; treat them as https.
    const candidate = /^https?:\/\//i.test(trimmed) || /^[a-z]+:/i.test(trimmed)
      ? trimmed
      : `https://${trimmed}`;
    const parsed = new URL(candidate);
    return ALLOWED_PROTOCOLS.includes(parsed.protocol);
  } catch {
    return false;
  }
}

/** Returns a safe, absolute URL or null when it cannot be trusted. */
export function safeExternalUrl(value: string): string | null {
  if (!value) return null;
  const trimmed = value.trim();
  if (!isSafeUrl(trimmed)) return null;
  const candidate = /^https?:\/\//i.test(trimmed) || /^[a-z]+:/i.test(trimmed)
    ? trimmed
    : `https://${trimmed}`;
  try {
    const parsed = new URL(candidate);
    if (!ALLOWED_PROTOCOLS.includes(parsed.protocol)) return null;
    return parsed.toString();
  } catch {
    return null;
  }
}

/** Strip unsafe URLs from arbitrary text (used for copy/profile-text export). */
export function sanitizeText(value: string): string {
  return value.replace(/\s+/g, " ").trim();
}

