export const SOCIAL_PLATFORMS_LIST = SOCIAL_PLATFORMS;

/**
 * Validates a profile's public URL segment. Slugs are generated by the server
 * (`<kebab-name>-<suffix>`, see lib/profile/slug.ts) — the length covers the
 * 40-character prefix plus the random suffix — and accepted unchanged when a
 * draft is round-tripped back to the editor.
 */
export const slugSchema = z
  .string()
  .min(3, "Use at least 3 characters")
  .max(64, "Keep it under 64 characters")
  .regex(
    /^[a-z0-9](?:[a-z0-9-]*[a-z0-9])?$/,
    "Lowercase letters, numbers and hyphens only",
  );

export const socialLinkSchema = z.object({
  id: z.string().min(1),
  platform: z.enum(SOCIAL_PLATFORMS),
  label: z.string().max(48, "Label is too long").default(""),
  url: z
    .string()
    .max(2048, "URL is too long")
    .refine((v) => v === "" || isSafeUrl(v), "Enter a valid http(s) or mailto URL"),
  visible: z.boolean().default(true),
});

export const featuredProjectSchema = z.object({
  id: z.string().min(1),
  title: z.string().max(80, "Title is too long").default(""),
  description: z.string().max(220, "Keep descriptions short").default(""),
  url: z
    .string()
    .max(2048, "URL is too long")
    .refine((v) => v === "" || isSafeUrl(v), "Enter a valid URL"),
  tag: z.string().max(24, "Tag is too long").default(""),
  imageUrl: z
    .string()
    .max(2048, "URL is too long")
    .refine((v) => v === "" || isSafeUrl(v), "Enter a valid image URL")
    .default(""),
});

export const themeSettingsSchema = z.object({
  theme: z.enum([
    "mono",
    "terminal",
    "editorial",
    "aurora",
    "noir",
    "sunrise",
    "forest",
    "ocean",
    "neon",
    "paper",
  ]),
  accent: z
    .string()
    .regex(/^#[0-9a-fA-F]{6}$/, "Use a 6-digit hex color")
    .default("#c6f24e"),
  fontPairing: z.enum([
    "geist",
    "editorial",
    "terminal",
    "system",
    "playfair",
    "grotesque",
    "lora",
    "jetbrains",
  ]),
  avatarShape: z.enum(["circle", "rounded", "square"]),
  background: z.enum([
    "plain",
    "subtle",
    "grid",
    "glow",
    "dots",
    "stripes",
    "mesh",
    "rings",
  ]),
  socialStyle: z.enum([
    "minimal",
    "outline",
    "solid",
    "soft",
    "elevated",
    "underline",
  ]),
});

export const profileSchema = z.object({
  name: z.string().min(1, "Add a name").max(60, "Name is too long"),
  slug: slugSchema,
  role: z.string().max(80, "Role is too long").default(""),
  tagline: z.string().max(120, "Tagline is too long").default(""),
  bio: z
    .string()
    .max(600, "Keep the bio under 600 characters")
    .default(""),
  location: z.string().max(60, "Location is too long").default(""),
  avatarUrl: z
    .string()
    .max(2048, "URL is too long")
    .refine((v) => v === "" || isSafeUrl(v), "Enter a valid image URL")
    .default(""),
  websiteUrl: z
    .string()
    .max(2048, "URL is too long")
    .refine((v) => v === "" || isSafeUrl(v), "Enter a valid URL")
    .default(""),
  skills: z.array(z.string().max(32)).max(24).default([]),
  interests: z.array(z.string().max(32)).max(24).default([]),
  socials: z.array(socialLinkSchema).max(12, "Up to 12 links").default([]),
  projects: z.array(featuredProjectSchema).max(6, "Up to 6 projects").default([]),
  sections: z
    .object({
      projects: z.boolean().default(true),
      skills: z.boolean().default(true),
      about: z.boolean().default(true),
      contact: z.boolean().default(true),
    })
    .default({ projects: true, skills: true, about: true, contact: true }),
  theme: themeSettingsSchema.default({
    theme: "editorial",
    accent: "#b8460e",
    fontPairing: "editorial",
    avatarShape: "circle",
    background: "subtle",
    socialStyle: "outline",
  }),
  cardLayout: z
    .enum([
      "classic",
      "banner",
      "minimal",
      "split",
      "poster",
      "spotlight",
      "frame",
      "duo",
    ])
    .default("classic"),
  profileDesign: z
    .enum(["editorial", "centered", "sidebar", "hero"])
    .default("editorial"),
  showQr: z.boolean().default(true),
});

export type ProfileSchema = z.infer<typeof profileSchema>;
export type SocialLinkInput = z.infer<typeof socialLinkSchema>;

export const aiGenerationInputSchema = z.object({
  type: z.enum(["bio", "tagline"]),
  role: z.string().trim().min(2, "Add your professional role").max(80),
  skills: z.array(z.string().min(1).max(32)).min(0).max(24),
  interests: z.array(z.string().min(1).max(32)).min(0).max(24),
  style: z.enum(["professional", "casual", "minimal", "creative"]),
  name: z.string().trim().max(60).optional().default(""),
});

/**
 * Resume text extracted in the browser and posted for AI mapping. The server
 * never sees PDF bytes — only this plain text, bounded so one request cannot
 * burn an unbounded number of tokens.
 */
export const resumeTextSchema = z.object({
  text: z.string().min(1, "No resume text was provided").max(20000),
});

export type AiGenerationInputSchema = z.infer<typeof aiGenerationInputSchema>;
